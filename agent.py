from langgraph.graph import StateGraph, START, END
from typing import Annotated, Sequence, TypedDict
from langchain_core.messages import BaseMessage, HumanMessage, AIMessage, ToolMessage, SystemMessage
from langchain.tools import tool
from langgraph.prebuilt import ToolNode, InjectedState
from langchain_groq import ChatGroq
from dotenv import load_dotenv
import os
from langgraph.graph.message import add_messages
import subprocess
from langgraph.checkpoint.memory import MemorySaver
from langgraph.types import interrupt

from utils import save_png, log_err, log_info

load_dotenv()

llm = ChatGroq(
    model = "openai/gpt-oss-120b",
    api_key = os.getenv("GROQ_API")
)

guard_llm = ChatGroq(
    model = "meta-llama/llama-prompt-guard-2-22m",
    api_key = os.getenv("GROQ_API")
)

DESKTOP = os.path.join(os.path.expanduser("~"),"Desktop")

class AgentState(TypedDict):
    messages: Annotated[Sequence[BaseMessage], add_messages]
    project_name: str
    last_action: str
    plan: str


@tool
def create_plan(content: str, project_name: str) -> bool:
    """Creates the plan.md file that lists all the step for the agent.

    Args:
        content (str): content of the file (in markdown)
        project_name (str): project name

    Returns:
        bool: acknowledgement
    """
    log_info("Invoking 'create_plan' tool")
    try:
        path = os.path.join(DESKTOP, project_name, "plan.md")
        with open(path, "w", encoding = "utf-8") as file:
            file.write(content)
        log_info("plan.md generated")

        return os.path.exists(path)
    except Exception as err:
        log_err(err)
        return False

@tool
def read_plan(project_name: str) -> dict[str, str]:
    """Reads the plan generated by the llm

    Args:
        project_name (str): project name

    Returns:
        bool: acknowledgement
    """
    log_info("Invoking 'read_plan'")
    try:
        path = os.path.join(DESKTOP, project_name, "plan.md")
        content = ""

        with open(path, "r") as file:
            line = file.readline()
            while line:
                content += line.strip() +"\n"

        return {"plan": content}
    except Exception as err:
        log_err(err)
        return False

@tool
def write_code(code: str, file_name_with_ext: str, project_name: str) -> bool:
    """Writes LLM generated code in the designated file (WARNING: overwrites the code if the file already exists)

    Args:
        code (str): code content
        file_name_with_ext (str): file name with extension (main.py index.js)
        project_name (str): project name

    Returns:
        bool: acknowledgement
    """
    log_info("Invoking 'write code' tool.")
    try:
        path = os.path.join(DESKTOP, project_name, file_name_with_ext)
        with open(path, "w", encoding = "utf-8") as file:
            file.write(code)

        log_info(f"Code written in {file_name_with_ext}")
        return os.path.exists(path)
    except Exception as err:
        log_err(err)
        return False

@tool
def create_project_dir(project_name: str) -> dict[str, str]:
    """Creates the project directory

    Args:
        project_name (str): project name

    Returns:
        dict[str, str]: project name as state dict
    """
    log_info("Invoking 'create_project_dir' tool")
    try:
        path = os.path.join(DESKTOP, project_name)
        if os.path.exists(path):
            return {"project_name":project_name}

        os.makedirs(path)
        log_info(f"Project created at {path}")

        return {"project_name":project_name}
    except Exception as err:
        log_err(err)
        return False

@tool
def run_commands(commands: list[str], project_name: str) -> bool:
    """Runs the command on the terminal (safely) using subprocess module

    Args:
        commands (list[str]): list of commands (eg: ['python','main.py'])
        project_name (str): project name

    Returns:
        bool: acknowledgement
    """
    log_info("Invoking 'run_commands' tool")
    try:
        log_info(f"Attempting to run command: {' '.join(commands)}")

        path = os.path.join(DESKTOP, project_name)
        results = subprocess.run(commands, capture_output = True, text = True, cwd = path)

        return True if results.returncode == 0 else False
    except Exception as err:
        log_err(err)
        return False

tools = [create_plan, read_plan, write_code, create_project_dir, run_commands]
llm_with_tools = llm.bind_tools(tools = tools, parallel_tool_calls = False)

def llm_invoke(state: AgentState) -> AgentState:
    sys_msg = SystemMessage(content = """
                    You are an autonomous coding assistant.

                Your job is to understand the user's request, plan the work,
                write code, and execute it using the available tools.

                AVAILABLE TOOLS:
                1. create_project_dir
                - Creates the project directory.
                - Must be called before writing project files.

                2. create_plan
                - Creates the plan.md file.

                3. read_plan
                - Reads the plan and appends its contents to the state.

                4. write_code
                - Writes generated code to the designated file.
                - WARNING: Overwrites existing code.

                5. run_commands
                - Executes terminal commands safely.

                STRICT RULES:
                - You may ONLY call tools that are registered and available to you.
                - CRITICAL: Never invent, rename, or modify a tool name.
                - Use the exact tool names provided in your tool definitions.
                - Never generate a tool call for an unavailable function.
                - Call only ONE tool at a time.
                - Wait for the tool result before deciding the next action.
                - Do not assume a tool succeeded without receiving its result.
                - If a tool fails, analyze the error before proceeding.
                - If no tool is required, respond normally.
                - CRITICAL: Please do not run the program file generated                                        
""")
    try:
        response = llm_with_tools.invoke([sys_msg]+state["messages"])
        state["messages"].append(response)
        return state
    except Exception as err:
        log_err(err)
        return state

def decision(state: AgentState) -> str:
    last_message = state["messages"][-1]
    if not isinstance(last_message, AIMessage):
        return END

    return "tool_node" if last_message.tool_calls else END

def inspect_prompt(state: AgentState) -> str:
    last_message = state["messages"][-1]
    if isinstance(last_message, AIMessage):
        log_info("Skipping prompt inspection")
        return "llm_invoke"

    response = guard_llm.invoke([
        {
            "role": "user",
            "content": last_message.content
        }
    ])
    if float(response.content) > 0.7:
        log_info(f"Malicious prompt detected (prob: {response.content})")
        return END
    else:
        log_info(f"Prompt inspection passed")
        return "llm_invoke"

def human_approval(state: AgentState) -> AgentState:
    last_message = state["messages"][-1]
    tool_calls = getattr(last_message,"tool_calls",[])

    log_info("Entering the human approval node")
    user_decision = interrupt(dict(
        user_question = "Tool call requested by agent",
        tool_calls = tool_calls
    ))
    log_info(f"User decision: {user_decision}")

    if user_decision.strip() == "approve":
        log_info(f"Tool call approved by user")
        return {"last_action":"approve"}
    else:
        log_info(f"Tool call rejected by user")
        return {"last_action":"reject", "messages": [AIMessage(content = "Tool call rejected by user.")]}

def human_approval_decision(state: AgentState) -> str:
    return "tool_node" if state["last_action"] == "approve" else "llm_invoke"


graph = StateGraph(AgentState)

graph.add_node("llm_invoke", llm_invoke)
graph.add_node("tool_node", ToolNode(tools = tools))
graph.add_node("router", lambda state: state)
graph.add_node("human_approval", human_approval)

graph.set_entry_point("router")
graph.add_conditional_edges("router",
                            inspect_prompt,
                            {
                                END: END,
                                "llm_invoke":"llm_invoke"
                            })
graph.add_conditional_edges("llm_invoke",
                            decision,
                            {
                                "tool_node":"human_approval",
                                END: END
                            })
graph.add_conditional_edges("human_approval",
                            human_approval_decision,
                            {
                                "tool_node":"tool_node",
                                "llm_invoke":"llm_invoke"
                            })
graph.add_edge("tool_node","router")


agent = graph.compile(checkpointer = MemorySaver())

